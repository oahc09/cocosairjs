/* Approximate emitted UTF-8 spans, not original source size or traced parse cost. */
const fs = require('node:fs');
const path = require('node:path');
const { decode } = require('@jridgewell/sourcemap-codec');
const { verifySourceBinding } = require('../../build/source-binding.cjs');
const { identity, writeNew } = require('./evidence.cjs');

function collect(root, bundle) {
    const binding = verifySourceBinding(root, bundle);
    if (!binding.matches)
        throw new Error('Source binding failed; use a fresh bundle, map and matching source checkout');
    const bytes = fs.readFileSync(bundle);
    const lines = bytes.toString('utf8').split('\n');
    const map = JSON.parse(fs.readFileSync(bundle + '.map', 'utf8'));
    const receipt = JSON.parse(fs.readFileSync(bundle + '.sources.json', 'utf8'));
    const counts = receipt.sources.map(({ path }) => ({ path, bytes: 0 }));
    const decoded = decode(map.mappings);
    let attributed = 0;
    for (let line = 0; line < decoded.length; line++) {
        const segments = decoded[line];
        const text = lines[line] ?? '';
        for (let i = 0; i < segments.length; i++) {
            const [start, source] = segments[i];
            if (source === undefined) continue;
            const end = segments[i + 1]?.[0] ?? text.length;
            if (!counts[source] || start > end || end > text.length) throw new Error('Invalid source-map segment');
            const size = Buffer.byteLength(text.slice(start, end), 'utf8');
            counts[source].bytes += size;
            attributed += size;
        }
    }
    if (attributed > bytes.length) throw new Error('Invalid overlapping source attribution');
    counts.sort((a, b) => b.bytes - a.bytes || Buffer.from(a.path).compare(Buffer.from(b.path)));
    return {
        scope: 'generated byte spans from source map; not parse/evaluate time',
        artifact: identity(bytes),
        bindingSha256: binding.receiptSha256,
        totalMappedSources: counts.length,
        attributedBytes: attributed,
        unmappedBytes: bytes.length - attributed,
        sources: counts,
    };
}

if (require.main === module) {
    try {
        if (process.argv.length !== 4) throw new Error('Usage: node closure.cjs <bundle.js> <new-output.json>');
        const root = path.resolve(__dirname, '../../..');
        writeNew(process.argv[3], collect(root, path.resolve(process.argv[2])));
    } catch (error) {
        console.error(error.message);
        process.exitCode = 1;
    }
}

module.exports = { collect };
