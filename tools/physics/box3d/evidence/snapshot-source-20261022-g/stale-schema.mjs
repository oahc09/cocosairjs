import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
const root = process.cwd();
const old = resolve(root, 'tools/physics/box3d/output/wasm-patch-release-20261022-e');
const manifest = JSON.parse(readFileSync(resolve(old, 'manifest.json')));
const lock = JSON.parse(readFileSync('tools/physics/box3d/versions.lock.json'));
const { default: factory } = await import(pathToFileURL(resolve(old, 'box3d-st.mjs')));
const { createBox3DBinding } = await import(pathToFileURL(resolve(root, 'src/air/physics/box3d/binding/facade.mjs')));
const wasm = readFileSync(resolve(old, 'box3d-st.wasm'));
const sha = (bytes) => createHash('sha256').update(bytes).digest('hex');
assert.equal(sha(wasm), manifest.artifacts.find((a) => a.path === 'box3d-st.wasm').sha256);
const module = await factory({ wasmBinary: wasm });
assert.throws(() => createBox3DBinding(module, manifest), { code: 'AIR_E_BOX3D_ABI' });
assert.throws(() => createBox3DBinding(module, { ...manifest, schemaSha256: lock.apiSchemaSha256 }), { code: 'AIR_E_BOX3D_ABI' });
const report = { status: 'PASS', scope: 'Current g facade rejects actual old e module with old and forged-current schema manifests; no new physics qualification', oldWasmSha256: sha(wasm), facadeSha256: sha(readFileSync('src/air/physics/box3d/binding/facade.mjs')), currentSchemaSha256: lock.apiSchemaSha256, oldSchemaSha256: manifest.schemaSha256, patchChainSha256: manifest.patchChainSha256, expectedRejections: 2 };
writeFileSync('tools/physics/box3d/output/snapshot-source-20261022-g/stale-schema.raw.json', JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report));
