import { generateFile } from './effect-json.mjs';
import { writeFileSync, readFileSync, mkdtempSync, unlinkSync, rmdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const example = fileURLToPath(new URL('../../examples/black-hole-accretion/', import.meta.url));
const temp = mkdtempSync(join(tmpdir(), 'cocosair-black-hole-effects-'));
const files = [];
try {
    const declarations = [];
    for (const name of ['disk', 'glow', 'stream', 'background']) {
        const output = join(temp, name + '.json'); files.push(output);
        const effect = generateFile(join(example, name + '.effect-spec.json'), output);
        declarations.push(`export const ${name}Effect = ${JSON.stringify(effect)};`);
    }
    const target = join(example, 'src/effects.generated.ts');
    const options = await prettier.resolveConfig(target);
    const generated = await prettier.format('// Generated by tools/build/black-hole-effects.mjs through the effect-json generator.\n' + declarations.join('\n') + '\n', { ...options, filepath: target });
    if (process.argv.includes('--check')) {
        if (readFileSync(target, 'utf8') !== generated) throw new Error('Black-hole effect module is stale; regenerate it.');
    } else { writeFileSync(target, generated); }
} finally {
    for (const file of files) { try { unlinkSync(file); } catch (error) { if (error.code !== 'ENOENT') throw error; } }
    rmdirSync(temp);
}
