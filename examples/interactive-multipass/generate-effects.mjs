/** Local reproducible authoring step; emits engine-native effect JSON modules. No runtime compiler.
 *  Run offline: node examples/interactive-multipass/generate-effects.mjs  (writes src/effects.generated.ts)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { buildEffectJson } from '../../tools/build/effect-json.mjs';

const read = (name) => readFileSync(new URL(`shaders/${name}.glsl`, import.meta.url), 'utf8').trim();
const position = { name: 'a_position', type: 'vec3', location: 0 };
const texCoord = { name: 'a_texCoord', type: 'vec2', location: 1 };
const vector = (name, value = [0, 0, 0, 0]) => ({ name, type: 'vec4', value });
const sampler = (name) => ({ name, type: 'sampler2D', value: 'black' });

const definitions = [
    {
        id: 'source',
        // Capture-path source quads. gain.x scales radiance above 1.0 for the RGBA16F case;
        // with RGBA8 the same values clamp exactly like the real pipeline.
        attributes: [position],
        uniforms: [vector('tint', [1, 1, 1, 1]), vector('gain', [1, 0, 0, 0])],
        vertex: read('source.vert'),
        fragment: read('source.frag'),
    },
    {
        id: 'display',
        // Fullscreen consumer of the captured color attachment.
        attributes: [position, texCoord],
        varyings: [{ name: 'v_uv', type: 'vec2' }],
        uniforms: [vector('params', [1, 0, 0, 0])], // x: exposure, y: tone-map switch
        samplers: [sampler('displayMap')],
        vertex: read('display.vert'),
        fragment: read('display.frag'),
    },
];

const json = (id) => {
    const { id: _omit, ...spec } = definitions.find((d) => d.id === id);
    return buildEffectJson({ name: `interactive-multipass-${id}`, ...spec });
};
const render = (id) => JSON.stringify(json(id), null, 2);
writeFileSync(
    new URL('./src/effects.generated.ts', import.meta.url),
    `// Generated by examples/interactive-multipass/generate-effects.mjs via tools/build/effect-json.mjs. Do not edit.
// Plain engine effect-JSON data; the runtime assigns it onto real EffectAsset instances.
export const sourceEffect = ${render('source')};
export const displayEffect = ${render('display')};
`,
);
console.log('effects.generated.ts written');
