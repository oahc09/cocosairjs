'use strict';
const fs = require('node:fs'),
    path = require('node:path');
const directory = __dirname;

async function generate() {
    const esbuild = require('esbuild');
    const prettier = require('prettier');
    const built = esbuild.buildSync({
        stdin: {
            contents: "export * from './examples/shared/shader-blocks.js'",
            resolveDir: path.resolve(directory, '../..'),
        },
        bundle: true,
        platform: 'node',
        format: 'cjs',
        write: false,
    });
    const module = { exports: {} };
    new Function('module', 'exports', 'require', built.outputFiles[0].text)(module, module.exports, require);
    const { makeUserEffectJson, standardVert, fragVariants } = module.exports;
    const vert = standardVert();
    // Both the pattern pass and the emboss pass are full-screen native MeshRenderer quads.
    for (const key of ['glsl3', 'glsl4']) {
        vert[key] = vert[key]
            .replace('cc_matViewProj * cc_matWorld * vec4(a_position, 1.0)', 'vec4(a_position.xy, 0.0, 1.0)')
            .replace('out mediump vec2 v_uv', 'out highp vec2 v_uv');
    }
    const emboss = makeUserEffectJson({
        name: 'air-e05-emboss',
        prog: 'air-e05-emboss-program',
        hash: 9000205,
        properties: {
            emboss0: { value: [1, 0, -0.5, 260] },
            emboss1: { value: [0.6, 0.3, 0, 0] },
            emboss2: { value: [640, 400, 0, 0] },
        },
        members: ['emboss0', 'emboss1', 'emboss2'].map((name) => ({ name, type: 16, count: 1 })),
        samplerTextures: [{ name: 'childTexture', type: 28, binding: 1 }],
        defines: [{ name: 'SHAPE_BOX', type: 'boolean' }],
    });
    const pattern = makeUserEffectJson({
        name: 'air-e05-child-pattern',
        prog: 'air-e05-child-pattern-program',
        hash: 9000206,
        properties: { pattern0: { value: [0, 0, 0, 0] } },
        members: [{ name: 'pattern0', type: 16, count: 1 }],
        defines: [],
    });
    const embossFrag = fs.readFileSync(path.join(directory, 'src', 'emboss.frag'), 'utf8');
    const patternFrag = fs.readFileSync(path.join(directory, 'src', 'pattern.frag'), 'utf8');
    const wrap = fragVariants;
    const embossVariants = wrap(embossFrag, 'precision highp float; void main(){gl_FragColor=vec4(0.0);}');
    const patternVariants = wrap(patternFrag, 'precision highp float; void main(){gl_FragColor=vec4(0.0);}');
    for (const key of ['glsl1', 'glsl3', 'glsl4']) {
        emboss.shaders[0][key] = { vert: vert[key], frag: embossVariants[key] };
        pattern.shaders[0][key] = { vert: vert[key], frag: patternVariants[key] };
    }
    const out = path.join(directory, 'src', 'effect.generated.ts');
    const rawOut =
        '// Generated by generate-effect.cjs from emboss.frag, pattern.frag and existing shader-blocks.\n' +
        'export const embossEffectDefinition = ' +
        JSON.stringify(emboss) +
        ';\n' +
        'export const patternEffectDefinition = ' +
        JSON.stringify(pattern) +
        ';\n';
    const config = await prettier.resolveConfig(out, { editorconfig: true });
    const formatted = await prettier.format(rawOut, { ...config, parser: 'typescript', filepath: out });
    fs.writeFileSync(out, formatted);
    return { out, shaderVariants: 6 };
}

module.exports = { generate };
if (require.main === module) {
    generate()
        .then((result) => console.log(JSON.stringify(result)))
        .catch((error) => {
            console.error(error);
            process.exitCode = 1;
        });
}
