'use strict';
const fs = require('node:fs'),
    path = require('node:path');
const directory = __dirname;

async function generate() {
    const esbuild = require('esbuild');
    const prettier = require('prettier');
    const built = esbuild.buildSync({
        stdin: {
            contents: "export * from './examples/shared/shader-blocks.js'",
            resolveDir: path.resolve(directory, '../..'),
        },
        bundle: true,
        platform: 'node',
        format: 'cjs',
        write: false,
    });
    const module = { exports: {} };
    new Function('module', 'exports', 'require', built.outputFiles[0].text)(module, module.exports, require);
    const { makeUserEffectJson, standardVert, fragVariants } = module.exports;
    const vert = standardVert();
    for (const key of ['glsl3', 'glsl4']) {
        vert[key] = vert[key]
            .replace('cc_matViewProj * cc_matWorld * vec4(a_position, 1.0)', 'vec4(a_position.xy, 0.0, 1.0)')
            .replace('out mediump vec2 v_uv', 'out highp vec2 v_uv');
    }
    const stages = [
        {
            name: 'air-w4-c03-trail',
            prog: 'air-w4-c03-trail-program',
            hash: 9000441,
            fragFile: 'trail_stage.frag',
            properties: {
                ts0: { value: [0, 0.667, 1, 0.5] },
                ts1: { value: [1, 0, 0.667, 1] },
                ts2: { value: [640, 400, 0, 1] },
                ts3: { value: [0.5, 0, 0, 0] },
            },
            members: ['ts0', 'ts1', 'ts2', 'ts3'].map((name) => ({ name, type: 16, count: 1 })),
            samplerTextures: [{ name: 'pointsTexture', type: 28, binding: 1 }],
        },
        {
            name: 'air-w4-c03-glass',
            prog: 'air-w4-c03-glass-program',
            hash: 9000442,
            fragFile: 'glass_stage.frag',
            properties: {
                // gs0: scale, rotation, refraction, thickness (mother defaults; main syncs live params)
                glass0: { value: [1, 0, 1, 0.5] },
                // glass1: blur, aberration, innerZoom, edgeSoftness
                glass1: { value: [0, 0.5, 1, 0.1] },
                // glass2: lightAngle, highlight, highlightSoftness, fresnel
                glass2: { value: [300, 0.05, 0.5, 0.2] },
                // glass3: fresnelSoftness, tintIntensity, preserveLum, cutout
                glass3: { value: [0.5, 0, 1, 0] },
                // glass4: tint rgb, layer-enabled (diagnostic independent of layer flag)
                glass4: { value: [0.95, 0.95, 1, 1] },
                // glass5: backing width, height, reserved
                glass5: { value: [640, 400, 0, 0] },
            },
            members: ['glass0', 'glass1', 'glass2', 'glass3', 'glass4', 'glass5'].map((name) => ({
                name,
                type: 16,
                count: 1,
            })),
            samplerTextures: [{ name: 'trailTexture', type: 28, binding: 1 }],
        },
    ];
    const outputs = [];
    for (const stage of stages) {
        const json = makeUserEffectJson({
            name: stage.name,
            prog: stage.prog,
            hash: stage.hash,
            properties: stage.properties,
            members: stage.members,
            samplerTextures: stage.samplerTextures,
            defines: ['SHAPE_BOX', 'USE_BLUR', 'USE_ABERRATION'].map((name) => ({ name, type: 'boolean' })),
        });
        const body = fs.readFileSync(path.join(directory, 'src', stage.fragFile), 'utf8');
        const variants = fragVariants(body, 'precision highp float; void main(){gl_FragColor=vec4(0.0);}');
        for (const key of ['glsl1', 'glsl3', 'glsl4']) {
            json.shaders[0][key] = { vert: vert[key], frag: variants[key] };
        }
        const varName = stage.name.split('-').pop() + 'EffectDefinition';
        outputs.push(`export const ${varName} = ${JSON.stringify(json)};`);
    }
    const out = path.join(directory, 'src', 'effect.generated.ts');
    const rawOut =
        '// Generated by generate-effect.cjs from trail/glass stage frags and shader-blocks.\n' +
        outputs.join('\n') +
        '\n';
    const config = await prettier.resolveConfig(out, { editorconfig: true });
    const formatted = await prettier.format(rawOut, { ...config, parser: 'typescript', filepath: out });
    fs.writeFileSync(out, formatted);
    return { out, shaderVariants: 6 };
}

module.exports = { generate };
if (require.main === module) {
    generate()
        .then((result) => console.log(JSON.stringify(result)))
        .catch((error) => {
            console.error(error);
            process.exitCode = 1;
        });
}
