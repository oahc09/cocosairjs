// C04 input-dissolve effect generator: two stages (procedural content, dissolve). Members and
// properties are derived from the ACTUAL GLSL Constants blocks below — run twice, byte-identical.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const directory = __dirname;
async function generate() {
    const esbuild = require('esbuild');
    const prettier = require('prettier');
    const built = esbuild.buildSync({
        stdin: {
            contents: "export * from './examples/shared/shader-blocks.js'",
            resolveDir: path.resolve(directory, '../..'),
        },
        bundle: true,
        platform: 'node',
        format: 'cjs',
        write: false,
    });
    const module = { exports: {} };
    new Function('module', 'exports', 'require', built.outputFiles[0].text)(module, module.exports, require);
    const { makeUserEffectJson, standardVert, fragVariants } = module.exports;
    const vert = standardVert();
    for (const key of ['glsl3', 'glsl4']) {
        vert[key] = vert[key]
            .replace('cc_matViewProj * cc_matWorld * vec4(a_position, 1.0)', 'vec4(a_position.xy, 0.0, 1.0)')
            .replace('out mediump vec2 v_uv', 'out highp vec2 v_uv');
    }
    const stages = [
        {
            name: 'air-w4-c04-content',
            prog: 'air-w4-c04-content-program',
            hash: 9000451,
            fragFile: 'content.frag',
            properties: {
                params: { value: [0, 8, 0, 0] },
                flags: { value: [1, 0, 0, 0] },
                params2: { value: [1, 1, 1, 1] },
            },
            members: ['params', 'flags', 'params2'].map((name) => ({ name, type: 16, count: 1 })),
            samplerTextures: [],
        },
        {
            name: 'air-w4-c04-dissolve',
            prog: 'air-w4-c04-dissolve-program',
            hash: 9000452,
            fragFile: 'dissolve.frag',
            properties: {
                params: { value: [0.35, 3, 0.25, 0] },
                flags: { value: [0, 1, 0, 1] },
            },
            members: ['params', 'flags'].map((name) => ({ name, type: 16, count: 1 })),
            samplerTextures: [{ name: 'sourceTexture', type: 28, binding: 1 }],
        },
    ];
    const outputs = [];
    for (const stage of stages) {
        const json = makeUserEffectJson({
            name: stage.name,
            prog: stage.prog,
            hash: stage.hash,
            properties: stage.properties,
            members: stage.members,
            samplerTextures: stage.samplerTextures,
        });
        const body = fs.readFileSync(path.join(directory, 'src', stage.fragFile), 'utf8');
        const variants = fragVariants(body, 'precision highp float; void main(){gl_FragColor=vec4(0.0);}');
        for (const key of ['glsl1', 'glsl3', 'glsl4']) json.shaders[0][key] = { vert: vert[key], frag: variants[key] };
        const varName = stage.name.split('-').pop() + 'EffectDefinition';
        outputs.push(`export const ${varName} = ${JSON.stringify(json)};`);
    }
    const out = path.join(directory, 'src', 'effect.generated.ts');
    const rawOut =
        '// Generated by generate-effect.cjs from content/dissolve frags and shader-blocks. DO NOT EDIT.\n' +
        outputs.join('\n') +
        '\n';
    fs.writeFileSync(out, rawOut);
    const formatted = await prettier.format(rawOut, {
        parser: 'typescript',
        ...(await prettier.resolveConfig(path.join(directory, 'src', 'effect.generated.ts'))),
    });
    fs.writeFileSync(out, formatted);
}
generate().catch((error) => {
    console.error(error);
    process.exitCode = 1;
});
