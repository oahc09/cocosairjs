'use strict';
const fs = require('node:fs'),
    path = require('node:path');
const directory = __dirname;

async function generate() {
    const esbuild = require('esbuild');
    const prettier = require('prettier');
    const built = esbuild.buildSync({
        stdin: {
            contents: "export * from './examples/shared/shader-blocks.js'",
            resolveDir: path.resolve(directory, '../..'),
        },
        bundle: true,
        platform: 'node',
        format: 'cjs',
        write: false,
    });
    const module = { exports: {} };
    new Function('module', 'exports', 'require', built.outputFiles[0].text)(module, module.exports, require);
    const { makeUserEffectJson, standardVert, fragVariants } = module.exports;
    const vert = standardVert();
    for (const key of ['glsl3', 'glsl4']) {
        vert[key] = vert[key]
            .replace('cc_matViewProj * cc_matWorld * vec4(a_position, 1.0)', 'vec4(a_position.xy, 0.0, 1.0)')
            .replace('out mediump vec2 v_uv', 'out highp vec2 v_uv');
    }
    const stages = [
        {
            name: 'air-w4-c01-holo',
            prog: 'air-w4-c01-holo-program',
            hash: 9000431,
            fragFile: 'holo_stage.frag',
            properties: {
                hs0: { value: [0.25, 0.5, 0.4, 1.5] },
                hs1: { value: [0.75, 0, 0.25, 1] },
                hs2: { value: [640, 400, 0, 0] },
            },
            members: ['hs0', 'hs1', 'hs2'].map((name) => ({ name, type: 16, count: 1 })),
        },
        {
            name: 'air-w4-c01-emboss',
            prog: 'air-w4-c01-emboss-program',
            hash: 9000432,
            fragFile: 'emboss_stage.frag',
            properties: {
                es0: { value: [-0.5, 260, 0.3, 1] },
                es1: { value: [640, 400, 0.25, 0] },
            },
            members: ['es0', 'es1'].map((name) => ({ name, type: 16, count: 1 })),
            samplerTextures: [{ name: 'holoTexture', type: 28, binding: 1 }],
        },
        {
            name: 'air-w4-c01-sparkle',
            prog: 'air-w4-c01-sparkle-program',
            hash: 9000433,
            fragFile: 'sparkle_stage.frag',
            properties: {
                ss0: { value: [70, 0.45, 0.2, 5] },
                ss1: { value: [0.35, 0.25, 1, 0] },
                ss2: { value: [640, 400, 0, 0] },
            },
            members: ['ss0', 'ss1', 'ss2'].map((name) => ({ name, type: 16, count: 1 })),
            samplerTextures: [{ name: 'embossTexture', type: 28, binding: 1 }],
        },
    ];
    const outputs = [];
    for (const stage of stages) {
        const json = makeUserEffectJson({
            name: stage.name,
            prog: stage.prog,
            hash: stage.hash,
            properties: stage.properties,
            members: stage.members,
            samplerTextures: stage.samplerTextures || [],
            defines: [{ name: 'SHAPE_BOX', type: 'boolean' }],
        });
        const body = fs.readFileSync(path.join(directory, 'src', stage.fragFile), 'utf8');
        const variants = fragVariants(body, 'precision highp float; void main(){gl_FragColor=vec4(0.0);}');
        for (const key of ['glsl1', 'glsl3', 'glsl4']) {
            json.shaders[0][key] = { vert: vert[key], frag: variants[key] };
        }
        const varName = stage.name.split('-').pop() + 'EffectDefinition';
        outputs.push(`export const ${varName} = ${JSON.stringify(json)};`);
    }
    const out = path.join(directory, 'src', 'effect.generated.ts');
    const rawOut =
        '// Generated by generate-effect.cjs from holo/emboss/sparkle stage frags and shader-blocks.\n' +
        outputs.join('\n') +
        '\n';
    const config = await prettier.resolveConfig(out, { editorconfig: true });
    const formatted = await prettier.format(rawOut, { ...config, parser: 'typescript', filepath: out });
    fs.writeFileSync(out, formatted);
    return { out, shaderVariants: 9 };
}

module.exports = { generate };
if (require.main === module) {
    generate()
        .then((result) => console.log(JSON.stringify(result)))
        .catch((error) => {
            console.error(error);
            process.exitCode = 1;
        });
}
